// Builds bases.js from blizzhackers/d2data (MIT): node tools/gen_bases.js <path-to-d2data> bases.js
// - WEAPON_BASES: every weapon base's speed (WSM) and animation class, for the attack-speed check.
// - ITEM_BASES: every weapon, armor, helm and shield base that can have sockets, for the stash's
//   Bases section (category, quality tier, max sockets, requirements).
// - TYPE_PARENTS: the game's item-type family tree, so a base can be matched to runeword types.
// - RW_TYPES: for each runeword, its rune count and the item types it can and can't go in.
const fs = require("fs");
const DIR = process.argv[2], OUT = process.argv[3];
const J = (f) => require(`${DIR}/json/${f}.json`);
const W = Object.values(J("weapons")), A = Object.values(J("armor")), T = Object.values(J("itemtypes")), R = Object.values(J("runes"));
const STR = J("localestrings-eng");

const weaponBases = {};
for (const w of W) {
  if (!w.name || !w.code || !w.wclass || (w.spawnable === 0 && !w.normcode)) continue;
  weaponBases[w.name] = {
    wsm: Number(w.speed) || 0,                       // weapon speed modifier
    wc: w.wclass,                                    // animation class when held normally
    wc2: w["2handedwclass"] || w.wclass,             // class when wielded two-handed (Barbarian 1-or-2 handed swords)
    th: w["2handed"] ? 1 : 0,                        // two-handed weapon
    oot: w["1or2handed"] ? 1 : 0,                    // Barbarian can hold it in one hand
    type: w.type,
  };
}

const typeParents = {};
for (const t of T) if (t.Code) typeParents[t.Code] = [t.Equiv1, t.Equiv2].filter(Boolean);
const chain = (code) => { const seen = new Set(); const q = [code]; while (q.length) { const c = q.shift(); if (!c || seen.has(c)) continue; seen.add(c); q.push(...(typeParents[c] || [])); } return seen; };

// Category shown in the picker, from the base's type family.
function category(type) {
  const ch = chain(type);
  if (ch.has("tors")) return "Body armor";
  if (ch.has("helm")) return "Helms";
  if (ch.has("shld")) return "Shields";
  if (ch.has("weap")) return "Weapons";
  return null;
}
const itemBases = {};
for (const b of [...W, ...A]) {
  if (!b.name || !b.code || !b.gemsockets || b.spawnable !== 1 || b.quest) continue;
  const cat = category(b.type);
  if (!cat) continue;
  const tier = b.code === b.ultracode ? "e" : b.code === b.ubercode ? "x" : "n";
  const e = { type: b.type, cat, tier, sock: b.gemsockets };
  if (b.levelreq) e.lvl = b.levelreq;
  if (b.reqstr) e.str = b.reqstr;
  if (b.reqdex) e.dex = b.reqdex;
  if (b.maxac) e.def = b.maxac;
  const lo = b["2handmindam"] || b.mindam, hi = b["2handmaxdam"] || b.maxdam;
  if (hi && cat === "Weapons") e.dmg = `${lo}-${hi}`;
  if (weaponBases[b.name]) e.wsm = weaponBases[b.name].wsm;
  itemBases[b.name] = e;
}

const rwTypes = {};
for (const r of R) {
  if (r.complete !== 1 || !r["*Rune Name"]) continue;
  let n = 0; for (let i = 1; i <= 6; i++) if (r[`Rune${i}`]) n++;
  const it = [], ex = [];
  for (let i = 1; i <= 6; i++) if (r[`itype${i}`]) it.push(r[`itype${i}`]);
  for (let i = 1; i <= 3; i++) if (r[`etype${i}`]) ex.push(r[`etype${i}`]);
  rwTypes[STR[r.Name] || r["*Rune Name"]] = { n, it, ex };
}
// Keep only the parts of the type tree the bases and runewords use.
const used = new Set(); for (const b of Object.values(itemBases)) chain(b.type).forEach((c) => used.add(c));
const tp = {}; for (const c of used) if (typeParents[c]?.length) tp[c] = typeParents[c];

fs.writeFileSync(OUT, `// Generated by tools/gen_bases.js from blizzhackers/d2data (MIT).
const WEAPON_BASES = ${JSON.stringify(weaponBases)};
const ITEM_BASES = ${JSON.stringify(itemBases)};
const TYPE_PARENTS = ${JSON.stringify(tp)};
const RW_TYPES = ${JSON.stringify(rwTypes)};
`);
console.log(Object.keys(weaponBases).length, "weapon bases,", Object.keys(itemBases).length, "socketable bases,", Object.keys(rwTypes).length, "runewords");
