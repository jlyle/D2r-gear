// Builds weapons.js (every D2R weapon base with its speed and animation class) from
// blizzhackers/d2data (MIT): node tools/gen_weapons.js <path-to-d2data> weapons.js
// Used by the attack-speed (IAS) breakpoint check.
const fs = require("fs");
const DIR = process.argv[2], OUT = process.argv[3];
const W = Object.values(require(`${DIR}/json/weapons.json`));
const out = {};
for (const w of W) {
  if (!w.name || !w.code || !w.wclass || w.spawnable === 0 && !w.normcode) continue;
  out[w.name] = {
    wsm: Number(w.speed) || 0,                       // weapon speed modifier
    wc: w.wclass,                                    // animation class when held normally
    wc2: w["2handedwclass"] || w.wclass,             // class when wielded two-handed (Barbarian 1-or-2 handed swords)
    th: w["2handed"] ? 1 : 0,                        // two-handed weapon
    oot: w["1or2handed"] ? 1 : 0,                    // Barbarian can hold it in one hand
    type: w.type,
  };
}
fs.writeFileSync(OUT, `// Generated by tools/gen_weapons.js from blizzhackers/d2data (MIT). Base weapon speed (WSM) and animation class.\nconst WEAPON_BASES = ${JSON.stringify(out)};\n`);
console.log(Object.keys(out).length, "weapon bases");
